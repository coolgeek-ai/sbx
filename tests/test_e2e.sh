#!/usr/bin/env bash
# End-to-end: a real Xray-core client (the same core v2rayN/v2rayNG use) connects to a real sing-box server
#   - REALITY + Vision (the camouflage target is a local TLS 1.3 server, no internet needed), chrome / firefox fingerprints
#   - Hysteria2: self-signed certificate + pinnedPeerCertSha256 (no allowInsecure)
#   - SS-2022
#   - Negative case: Xray must reject unencrypted VLESS on a public IP (reproduces "vless without TLS or other encryption is prohibited")
set -uo pipefail
source "$(dirname "$0")/lib.sh"; require_bins
XRAY="$BINDIR/xray"; SB="$SBX_BIN"; cd "$WORK" || exit 1

sbx add reality -p 38443 --sni localhost >/dev/null 2>&1
sbx add hy2     -p 38444                 >/dev/null 2>&1
sbx add ss      -p 38445                 >/dev/null 2>&1
# trojan / vless-ws normally need a domain + ACME; a self-signed certificate stands in here and the client trusts it via a pin (verifies the server TLS/WS/Trojan wiring and the link parameters)
bash -c '
  source "$0/sbx.sh"
  make_selfsigned dom example.com
  node_save tj trojan 38446 pass=abc123XYZ domain=example.com cert=$(self_dir dom)/cert.pem key=$(self_dir dom)/key.pem
  node_save ws vless-ws 38447 uuid=$("$BIN" generate uuid) domain=example.com path=/Ab3xY9qLm2 cert=$(self_dir dom)/cert.pem key=$(self_dir dom)/key.pem
  apply_config' "$ROOT" >/dev/null 2>&1 || { bad "trojan/ws node creation failed"; finish; exit 1; }
N="$SBX_ETC/nodes"

openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes -subj /CN=localhost -days 2 -keyout lk.pem -out lc.pem 2>/dev/null
openssl s_server -accept 38450 -cert lc.pem -key lk.pem -tls1_3 -alpn h2 -www >/dev/null 2>&1 & PIDS+=($!)
mkdir -p www; echo e2e-ok >www/index.html
python3 -m http.server 38999 --bind 127.0.0.1 --directory www >/dev/null 2>&1 & PIDS+=($!)

# The server config is exactly what the script generates; only the REALITY handshake target points to localhost
jq '(.inbounds[]|select(.type=="vless")|.tls.reality.handshake)={server:"127.0.0.1",server_port:38450}' "$SBX_ETC/config.json" >srv.json
"$SB" check -c srv.json || { bad "server config is invalid"; finish; exit 1; }
"$SB" run -c srv.json >srv.log 2>&1 & PIDS+=($!)
sleep 2

U=$(jq -r .uuid "$N/reality-38443.json"); PUB=$(jq -r .pub "$N/reality-38443.json"); SID=$(jq -r .sid "$N/reality-38443.json")
HP=$(jq -r .pass "$N/hysteria2-38444.json"); PIN=$(jq -r .pin "$N/hysteria2-38444.json" | tr -d ':' | tr 'A-F' 'a-f')
SP=$(jq -r .pass "$N/ss2022-38445.json")

try() {  # try NAME OUTBOUND_JSON PORT
  cat >"c-$1.json" <<EOT
{"log":{"loglevel":"warning"},"inbounds":[{"port":$3,"listen":"127.0.0.1","protocol":"socks","settings":{"udp":true}}],"outbounds":[$2]}
EOT
  "$XRAY" run -c "c-$1.json" >"c-$1.log" 2>&1 & local xp=$!; PIDS+=("$xp"); sleep 2
  if [[ $(curl -s --max-time 8 --socks5-hostname "127.0.0.1:$3" http://127.0.0.1:38999/) == e2e-ok ]]; then ok "$1"; else bad "$1"; tail -n 5 "c-$1.log" srv.log; fi
  kill "$xp" 2>/dev/null; sleep 1
}

echo "== Xray $("$XRAY" version | head -n1 | awk '{print $2}') -> sing-box $("$SB" version | head -n1 | awk '{print $3}') =="
for fp in chrome firefox; do
  try "reality-vision-$fp" '{"protocol":"vless","settings":{"vnext":[{"address":"127.0.0.1","port":38443,"users":[{"id":"'"$U"'","encryption":"none","flow":"xtls-rprx-vision"}]}]},"streamSettings":{"network":"tcp","security":"reality","realitySettings":{"serverName":"localhost","fingerprint":"'"$fp"'","publicKey":"'"$PUB"'","shortId":"'"$SID"'"}}}' 39082
done
try "hysteria2-self-signed-pin-only" '{"protocol":"hysteria","settings":{"address":"127.0.0.1","port":38444,"version":2},"streamSettings":{"network":"hysteria","security":"tls","tlsSettings":{"serverName":"www.bing.com","alpn":["h3"],"pinnedPeerCertSha256":"'"$PIN"'"},"hysteriaSettings":{"version":2,"auth":"'"$HP"'"}}}' 39083
try "ss2022" '{"protocol":"shadowsocks","settings":{"servers":[{"address":"127.0.0.1","port":38445,"method":"2022-blake3-aes-128-gcm","password":"'"$SP"'"}]}}' 39084

echo "== Real share links generated by the script -> v2rayNG parsing rules -> Xray outbound -> real sing-box server =="
# tests/link2xray.py implements link parsing following the v2rayNG 2.3.14 source (FmtBase / Hysteria2Fmt / TrojanFmt / ShadowsocksFmt / CoreOutboundBuilder),
# so this tests the parameter names and values in the links themselves, not a hand-written client config.
DOMPIN=$(openssl x509 -in "$SBX_ETC/certs/_self/dom/cert.pem" -noout -fingerprint -sha256 | cut -d= -f2)
i=0
for n in reality-38443 hysteria2-38444 ss2022-38445 tj ws; do
  f="$N/$n.json"; link=$(bash -c "source \"$ROOT/sbx.sh\"; node_link $f" 2>/dev/null); i=$((i+1)); cp=$((39500+i))
  if ! ob=$(python3 "$ROOT/tests/link2xray.py" "$link" 127.0.0.1 "$(jq -r .port "$f")" 2>&1); then bad "link parsing failed for $n: $ob"; continue; fi
  if [[ $n == tj || $n == ws ]]; then ob=$(jq --arg p "$DOMPIN" '.streamSettings.tlsSettings.pinnedPeerCertSha256=$p' <<<"$ob"); fi
  try "link-$n" "$ob" "$cp"
done

echo "== Negative cases (regression sentinels) =="
echo '{"outbounds":[{"tag":"proxy","protocol":"vless","settings":{"vnext":[{"address":"8.8.8.8","port":443,"users":[{"id":"'"$U"'","encryption":"none"}]}]},"streamSettings":{"network":"tcp"}}]}' >neg.json
msg=$("$XRAY" run -test -c neg.json 2>&1 || true)
if grep -q 'vless without TLS or other encryption is prohibited' <<<"$msg"; then ok "Xray still rejects plaintext VLESS on a public IP (this script never generates such nodes)"; else bad "Xray behavior changed: plaintext VLESS on a public IP is no longer rejected; update docs/COMPATIBILITY.md"; fi

# Sentinel #2: Xray rejects allowInsecure even together with a pin => links must never contain insecure=1 (v2rayN strips it itself for the Xray core)
cat >neg2.json <<EOT
{"outbounds":[{"protocol":"hysteria","settings":{"address":"127.0.0.1","port":38444,"version":2},"streamSettings":{"network":"hysteria","security":"tls","tlsSettings":{"serverName":"www.bing.com","allowInsecure":true,"pinnedPeerCertSha256":"$PIN"},"hysteriaSettings":{"version":2,"auth":"$HP"}}}]}
EOT
msg=$("$XRAY" run -test -c neg2.json 2>&1 || true)
if grep -q 'allowInsecure.*has been removed' <<<"$msg"; then ok "Xray still rejects allowInsecure (even with a pin)"; else bad "Xray behavior changed: allowInsecure is no longer rejected; re-evaluate the hy2 link policy (docs/COMPATIBILITY.md)"; fi
finish
